"""Build the bounded, flash-resident Liang trie from the pinned English rules."""
from pathlib import Path
import hashlib
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/data/hyph-en-us.tex'
SHA = 'f4ffcd96c5cbc886bdad23f95dcae8edc3cd3620eae62f7946eceda97c4e68f8'


def generate():
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA:
        raise ValueError('English pattern checksum mismatch')
    text = re.sub(r'%[^\n]*', '', data.decode())
    patterns = re.search(r'\\patterns\s*\{(.*?)\}', text, re.S)[1].split()
    root = {}
    for pattern in patterns:
        letters, values = '', [0]
        for ch in pattern:
            if ch.isdigit():
                values[-1] = max(values[-1], int(ch))
            else:
                letters += ch
                values.append(0)
        node = root
        for letter in letters:
            node = node.setdefault(letter, {})
        previous = node.get('', [0] * len(values))
        node[''] = [max(a, b) for a, b in zip(previous, values)]
    nodes, letters, records, values = [root], ['.'], [], []
    for node in nodes:
        offset = 65535
        if '' in node:
            offset = len(values)
            values.extend([len(node[''])] + node[''])
        children = sorted(k for k in node if k)
        records.append((len(nodes) if children else 0, offset,
                        len(children), letters[len(records)]))
        for key in children:
            nodes.append(node[key])
            letters.append(key)
    assert len(nodes) < 65535 and len(values) < 65535
    lines = ['// Generated by tools/build_hyphenation.py; do not edit.',
             '// English patterns: Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken.',
             '// See licenses/English-hyphenation.txt and tools/data/hyph-en-us.tex.',
             '// Source SHA-256: ' + SHA, '#pragma once', '#include <cstdint>',
             'namespace english_patterns {',
             'struct Node { uint16_t child, values; uint8_t count; char letter; };',
             'static const Node NODES[] = {']
    lines += ["{%d,%d,%d,'%s'}," % row for row in records]
    lines += ['};', 'static const uint8_t VALUES[] = {']
    lines += [','.join(str(v) for v in values[i:i+32]) + ','
              for i in range(0, len(values), 32)]
    lines += ['};', 'struct Exception { const char* word; uint64_t breaks; };',
              'static const Exception EXCEPTIONS[] = {']
    raw = re.search(r'\\hyphenation\s*\{(.*?)\}', text, re.S)[1].split()
    for item in sorted(raw, key=lambda s: s.replace('-', '')):
        word, bits = '', 0
        for ch in item:
            if ch == '-':
                bits |= 1 << len(word)
            else:
                word += ch
        lines.append('{"%s",%dULL},' % (word, bits))
    lines += ['};', '} // namespace english_patterns']
    output = '\n'.join(lines) + '\n'
    destination = ROOT / 'src/en_us_patterns.h'
    if '--check' in sys.argv:
        assert destination.read_text() == output, 'Regenerate English trie'
    else:
        destination.write_text(output)
    print(f'English: {len(patterns)} rules, {len(nodes)} nodes, {len(values)} value bytes')


if __name__ == '__main__':
    generate()

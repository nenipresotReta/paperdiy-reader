"""Build the bounded, flash-resident Liang trie from the pinned English rules."""
from pathlib import Path
import hashlib
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/data/hyph-en-us.tex'
SHA = 'f4ffcd96c5cbc886bdad23f95dcae8edc3cd3620eae62f7946eceda97c4e68f8'


def generate(british=False):
    source = ROOT / 'tools/data/hyph-en-gb.tex' if british else SOURCE
    checksum = 'e95bb4ab350f620c41c231c4785d7bdb4f91949d3e631b30e08b3ead3c340a52' if british else SHA
    namespace = 'english_gb_patterns' if british else 'english_patterns'
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError('English pattern checksum mismatch')
    text = re.sub(r'%[^\n]*', '', data.decode())
    patterns = re.search(r'\\patterns\s*\{(.*?)\}', text, re.S)[1].split()
    root = {}
    for pattern in patterns:
        letters, values = '', [0]
        for ch in pattern:
            if ch.isdigit():
                values[-1] = max(values[-1], int(ch))
            else:
                letters += ch
                values.append(0)
        node = root
        for letter in letters:
            node = node.setdefault(letter, {})
        previous = node.get('', [0] * len(values))
        node[''] = [max(a, b) for a, b in zip(previous, values)]
    nodes, letters, records, values = [root], ['.'], [], []
    for node in nodes:
        offset = 65535
        if '' in node:
            offset = len(values)
            values.extend([len(node[''])] + node[''])
        children = sorted(k for k in node if k)
        records.append((len(nodes) if children else 0, offset,
                        len(children), letters[len(records)]))
        for key in children:
            nodes.append(node[key])
            letters.append(key)
    assert len(nodes) < 65535 and len(values) < 65535
    notice = ['// Generated by tools/build_hyphenation.py; do not edit.',
             ('// British English patterns: Copyright (C) 1992, 1996, 2005, 2016 Dominik Wujastyk, Graham Toal.' if british else '// English patterns: Copyright (C) 1990, 2004, 2005 Gerard D.C. Kuiken.'),
             ('// See licenses/British-English-hyphenation.txt and tools/data/hyph-en-gb.tex.' if british else '// See licenses/English-hyphenation.txt and tools/data/hyph-en-us.tex.'),
             '// Source SHA-256: ' + checksum]
    lines = notice + ['namespace ' + namespace + ' {', 'const Node NODES[%d] = {' % len(records)]
    lines += ["{%d,%d,%d,'%s'}," % row for row in records]
    lines += ['};', 'const uint8_t VALUES[%d] = {' % len(values)]
    lines += [','.join(str(v) for v in values[i:i+32]) + ','
              for i in range(0, len(values), 32)]
    raw = re.search(r'\\hyphenation\s*\{(.*?)\}', text, re.S)[1].split()
    lines += ['};', 'const Exception EXCEPTIONS[%d] = {' % len(raw)]
    for item in sorted(raw, key=lambda s: s.replace('-', '')):
        word, bits = '', 0
        for ch in item:
            if ch == '-':
                bits |= 1 << len(word)
            else:
                word += ch
        lines.append('{"%s",%dULL},' % (word, bits))
    lines += ['};', '} // namespace ' + namespace]
    header = notice + ['#pragma once', '#include <cstdint>',
                       'namespace ' + namespace + ' {',
                       'struct Node { uint16_t child, values; uint8_t count; char letter; };',
                       'struct Exception { const char* word; uint64_t breaks; };',
                       '// Defined once in english_hyphenation.cpp; never duplicate in a consumer TU.',
                       'extern const Node NODES[%d];' % len(records),
                       'extern const uint8_t VALUES[%d];' % len(values),
                       'extern const Exception EXCEPTIONS[%d];' % len(raw),
                       '} // namespace ' + namespace]
    print(f'{namespace}: {len(patterns)} rules, {len(nodes)} nodes, {len(values)} value bytes')
    return '\n'.join(header) + '\n', '\n'.join(lines) + '\n'


def outputs():
    us_header, us_source = generate()
    gb_header, gb_source = generate(True)
    implementation = ('// Generated by tools/build_hyphenation.py; do not edit.\n'
                      '// Sole definitions for the unchanged US/GB Liang pattern tables.\n'
                      '#include "en_us_patterns.h"\n#include "en_gb_patterns.h"\n'
                      'static_assert(sizeof(english_patterns::Node)==6, "US trie record layout");\n'
                      'static_assert(sizeof(english_gb_patterns::Node)==6, "GB trie record layout");\n'
                      + us_source + gb_source)
    return {'src/en_us_patterns.h': us_header, 'src/en_gb_patterns.h': gb_header,
            'src/english_hyphenation.cpp': implementation}


if __name__ == '__main__':
    for name, output in outputs().items():
        destination = ROOT / name
        if '--check' in sys.argv:
            assert destination.read_text() == output, 'Regenerate English trie: ' + name
        else:
            destination.write_text(output)
